"""Run only the new dynamic phase. Historical 101-MOS data are read-only."""
from pathlib import Path
from itertools import product
import argparse,json,time
from gamma_sar_exact import OUT,write_csv
from gamma_sar_circuit import build,analyze,comparator_build,comparator_analyze
from gamma_sar_batch import batch_execute
from gamma_sky130 import dump,compress_trace,fast_raw

BASE={'limit':15,'scheme':'sar','transfer_kind':'redistribution','ref_kind':'capacitive',
      'store_ff':1000,'ref_ff':1000,'cmp_w':.42,'cmp_l':.15,'maxstep_ns':.5}
SMALL=[-13,-4,0,4,13]

def run(configs,kind='cell',workers=2):
    cases=[]
    for cfg in configs:
        deck,meta=(comparator_build if kind=='comparator' else build)(cfg)
        cases.append((deck,meta,OUT/'spice'/cfg['label']))
    def process(r,n,x,p):
        try:
            m=(comparator_analyze if kind=='comparator' else analyze)(r,n,x);m['run']=str(p.relative_to(OUT.parent.parent))
        except Exception as e:
            m={'cfg':r['meta']['cfg'],'unresolved':str(e),'run':str(p.relative_to(OUT.parent.parent))}
        dump(p/'metrics.json',m)
        if 'unresolved' not in m:compress_trace(p/'output.raw')
        print(p.name,'unresolved' if 'unresolved' in m else
          (f"cmp {m['correct_nonzero']}/{m['nonzero']} {m['mean_comparison_fj']:.1f} fJ" if kind=='comparator' else
           f"q {m['quotient_correct']}/{m['states']} charge {m['transfer_correct']} class {m['class_correct']} sleep {m['sleep_correct']} E {m['mean_event_fj']:.1f} fJ idle {m['idle_power_nw']:.3f} nW"),flush=True)
        return {**r,'observations':m.get('observations',[{'unresolved':m.get('unresolved')}]),'summary':m}
    rows=batch_execute(cases,workers=workers,processor=process)
    # Cached summaries were generated by the same literal-deck fingerprint.
    return [r['summary'] for r in rows]

def nominal(workers=2):
    cfgs=[]
    for limit in (7,15):cfgs.append({**BASE,'limit':limit,'label':f'range{limit}_sar','group':'range'})
    cfgs.append({**BASE,'limit':31,'transfer_kind':'binary_sc','period_ns':300,'maxstep_ns':1,
      'label':'range31_binary_compact','group':'range_compact'})
    for scheme in ('bank','binary_residual'):
        cfgs.append({**BASE,'scheme':scheme,'label':'bank_driven' if scheme=='bank' else 'scheme_'+scheme,
          'ref_driver_w':4.2 if scheme=='bank' else .42,'group':'scheme_driven' if scheme=='bank' else 'scheme'})
    for ff in (150,300,500):cfgs.append({**BASE,'states':SMALL,'ref_ff':ff,'label':f'ref_cap{ff}','group':'reference'})
    for ref in ('precharged','shared_static'):
        cfgs.append({**BASE,'states':SMALL,'ref_kind':ref,'label':'ref_'+ref,'group':'reference'})
    for transfer in ('binary_sc','gated_current','segmented_sc'):
        cfgs.append({**BASE,'states':SMALL,'transfer_kind':transfer,'label':'transfer_'+transfer,'group':'transfer'})
    rows=run(cfgs,workers=workers);dump(OUT/'nominal.json',rows)
    return rows

def robustness(workers=2):
    # Diagnostic selection is frozen independently of PVT outcomes. No nominal
    # only win is claimed, and all four correctness axes remain separate.
    selected=dict(BASE)
    dump(OUT/'selected_config.json',{'config':selected,'selection_scope':'Frozen diagnostic SAR candidate, not a robust winner; no post-PVT retuning.'})
    cfgs=[]
    for i,(corner,voltage,temp) in enumerate(product(('tt','ss','ff','sf','fs'),(1.62,1.8,1.9),(-40,25,100))):
        cfgs.append({**selected,'states':SMALL,'corner':corner,'vdd':voltage,'temp':temp,'label':f'pvt{i:02d}','group':'pvt'})
    for mode in ('transistor','capacitor','reference'):
        for j in range(8):
            cfg={**selected,'states':SMALL,'seed':51001+j,'label':f'mm_{mode}{j:02d}','group':'mismatch','mismatch_mode':mode}
            if mode=='transistor':cfg['pdk_mm']=True
            elif mode=='capacitor':
                cfg['cap_sigma']=.01;cfg['fixed_topology_caps']=True;cfg['label']=f'mm_capacitor_fixed{j:02d}'
            else:cfg['ratio_sigma']=.01
            cfgs.append(cfg)
    # Separate deterministic reference-offset and finer-step controls.
    for offset in (-.5,-.25,.25,.5):cfgs.append({**selected,'states':SMALL,'ref_offset_units':offset,'label':f'offset{offset:g}','group':'reference_offset'})
    cfgs.append({**selected,'states':SMALL,'maxstep_ns':.1,'label':'fine_step','group':'timestep'})
    rows=run(cfgs,workers=workers);dump(OUT/'robustness.json',rows);return rows

def comparator_robustness(workers=2):
    cfgs=[]
    for i,(corner,voltage,temp) in enumerate(product(('tt','ss','ff','sf','fs'),(1.62,1.8,1.9),(-40,25,100))):
        cfgs.append({'cmp_w':.42,'cmp_l':.15,'corner':corner,'vdd':voltage,'temp':temp,'label':f'cmp_pvt{i:02d}','group':'comparator_pvt'})
    for j in range(8):cfgs.append({'cmp_w':.42,'cmp_l':.15,'pdk_mm':True,'seed':61001+j,'label':f'cmp_mm{j:02d}','group':'comparator_mismatch'})
    rows=run(cfgs,kind='comparator',workers=workers);dump(OUT/'comparator_robustness.json',rows);return rows

def main():
    p=argparse.ArgumentParser();p.add_argument('--stage',choices=['nominal','robust','comparator','all'],default='all');p.add_argument('--workers',type=int,default=2);a=p.parse_args()
    OUT.mkdir(parents=True,exist_ok=True)
    if a.stage in ('nominal','all'):nominal(a.workers)
    if a.stage in ('robust','all'):robustness(a.workers)
    if a.stage in ('comparator','all'):comparator_robustness(a.workers)

if __name__=='__main__':main()
